/**
 * Encrypt a text key natively using the browser's Web Crypto API with SHA-256
 */
export async function verifyLicenseClient(key: string): Promise<boolean> {
  const normalized = key.trim();
  if (!normalized) return false;
  
  try {
    const encoder = new TextEncoder();
    const data = encoder.encode(normalized);
    const hashBuffer = await crypto.subtle.digest("SHA-256", data);
    const hashArray = Array.from(new Uint8Array(hashBuffer));
    const hashHex = hashArray.map(b => b.toString(16).padStart(2, "0")).join("");
    return ENCRYPTED_REGISTRY.includes(hashHex);
  } catch (error) {
    // Basic JS hashing fallback for environments where Web Crypto isn't loaded (e.g. non-localhost HTTP)
    let hash = 0;
    for (let i = 0; i < normalized.length; i++) {
      const char = normalized.charCodeAt(i);
      hash = (hash << 5) - hash + char;
      hash |= 0;
    }
    // Return false or standard lookup if Web Crypto fails, but practically Web Crypto is 100% available on modern browsers.
    return false;
  }
}
